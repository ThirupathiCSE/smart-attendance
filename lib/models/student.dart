class Student {
  String rollNo;
  String name;
  String branch;
  String section;
  String mobile;
  String email;
  String semester;
  String academicYear;

  Student({
    required this.rollNo,
    required this.name,
    required this.branch,
    required this.section,
    required this.mobile,
    required this.email,
    required this.semester,
    required this.academicYear,
  });
}
